def phone_variants(phone):
    """Как люди на самом деле вводят номер: «8 912…», «+7(912)…», «912…» — для персон разного уровня."""
    digits = phone[-10:]
    return [f"+7{digits}", f"8{digits}", f"8 ({digits[:3]}) {digits[3:6]}-{digits[6:8]}-{digits[8:]}", f"+7 {digits[:3]} {digits[3:6]} {digits[6:]}", digits]


